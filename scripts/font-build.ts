// Turn a PixelLab font atlas (create_font: a grid of 80 glyph cells, row-major, in the order
// below) into a glyph module the game draws with: src/ui/fonts/<name>.ts. Each glyph is trimmed
// to its ink columns so the font is proportional; rows keep the cell's vertical position, cropped
// to the rows any glyph uses, so the baseline stays shared.
//
// Usage: npx vite-node scripts/font-build.ts <atlas.png> <name> [--preview "sample text"]
//   --preview also writes art/raw/fonts/preview-<name>.png (the sample at 4x) to look at.
import fs from 'node:fs';
import path from 'node:path';
import { decodePNG, encodePNG, type Img } from './lib/png';

const ORDER = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz.,!?:;\'"-+()0123456789/%*=_$';
// the atlas comes back 8 glyphs wide and 10 tall (the tool docs say 10x8)
const COLS = 8, ROWS = 10;

const [atlasPath, name, flag, sample] = process.argv.slice(2);
if (!atlasPath || !name) {
  console.error('usage: vite-node scripts/font-build.ts <atlas.png> <name> [--preview "text"]');
  process.exit(2);
}

const img: Img = decodePNG(fs.readFileSync(atlasPath));
const cw = img.w / COLS, chh = img.h / ROWS;
const ink = (x: number, y: number) => img.data[(y * img.w + x) * 4 + 3] > 127;

interface Cell { ch: string; x0: number; x1: number; rows: boolean[][] }
const cells: Cell[] = [];
let top = chh, bottom = 0;
for (let i = 0; i < ORDER.length; i++) {
  const cx = (i % COLS) * cw, cy = Math.floor(i / COLS) * chh;
  const rows: boolean[][] = [];
  let x0 = cw, x1 = -1;
  for (let y = 0; y < chh; y++) {
    const r: boolean[] = [];
    for (let x = 0; x < cw; x++) {
      const on = ink(cx + x, cy + y);
      r.push(on);
      if (on) {
        x0 = Math.min(x0, x);
        x1 = Math.max(x1, x);
        top = Math.min(top, y);
        bottom = Math.max(bottom, y);
      }
    }
    rows.push(r);
  }
  cells.push({ ch: ORDER[i], x0, x1, rows });
}

// baseline: the lowest ink row of the capitals
let base = 0;
for (const c of cells) if (/[A-Z]/.test(c.ch)) c.rows.forEach((r, y) => { if (r.some(Boolean)) base = Math.max(base, y); });
// cap height: from the highest ink row of the capitals
let capTop = chh;
for (const c of cells) if (/[A-Z]/.test(c.ch)) c.rows.forEach((r, y) => { if (r.some(Boolean)) capTop = Math.min(capTop, y); });

const glyphs: Record<string, string> = {};
for (const c of cells) {
  if (c.x1 < 0) continue;
  const rows: string[] = [];
  for (let y = top; y <= bottom; y++) rows.push(c.rows[y].slice(c.x0, c.x1 + 1).map((b) => (b ? '#' : '.')).join(''));
  glyphs[c.ch] = rows.join('|');
}

const height = bottom - top + 1;
const meta = { height, baseline: base - top, cap: base - capTop + 1, space: Math.max(2, Math.round((base - capTop + 1) * 0.4)) };
const outDir = path.resolve('src/ui/fonts');
fs.mkdirSync(outDir, { recursive: true });
const lines = Object.entries(glyphs).map(([ch, g]) => `  ${JSON.stringify(ch)}: '${g}',`);
const ts = `// Generated by scripts/font-build.ts from a PixelLab font atlas (${path.basename(atlasPath)}). Do not edit by
// hand: rebuild, or add glyphs in src/ui/font.ts. Rows top to bottom, '#' is ink.
export const META = ${JSON.stringify(meta)} as const;

export const GLYPHS: Record<string, string> = {
${lines.join('\n')}
};
`;
fs.writeFileSync(path.join(outDir, `${name}.ts`), ts);
console.log(`wrote src/ui/fonts/${name}.ts`, meta, Object.keys(glyphs).length, 'glyphs');

if (flag === '--preview') {
  const text = (sample ?? 'The Quick Brown Fox').split('\\n');
  const gap = 1, k = 4;
  const lineH = height + 3;
  const widthOf = (s: string) => [...s].reduce((w, ch) => w + (ch === ' ' ? meta.space : (glyphs[ch]?.split('|')[0].length ?? 3)) + gap, 0);
  const W = Math.max(...text.map(widthOf)) + 4, H = text.length * lineH + 4;
  const px = new Uint8Array(W * k * H * k * 4);
  const put = (x: number, y: number, rgb: number[]) => {
    for (let yy = 0; yy < k; yy++) for (let xx = 0; xx < k; xx++) {
      const o = (((y * k + yy) * W * k) + x * k + xx) * 4;
      px[o] = rgb[0]; px[o + 1] = rgb[1]; px[o + 2] = rgb[2]; px[o + 3] = 255;
    }
  };
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) put(x, y, [253, 240, 214]);
  text.forEach((s, li) => {
    let x = 2;
    for (const ch of s) {
      if (ch === ' ') { x += meta.space + gap; continue; }
      const g = glyphs[ch];
      if (!g) { x += 3 + gap; continue; }
      const rows = g.split('|');
      rows.forEach((r, y) => { for (let i = 0; i < r.length; i++) if (r[i] === '#') put(x + i, 2 + li * lineH + y, [22, 62, 70]); });
      x += rows[0].length + gap;
    }
  });
  const out = path.resolve('art/raw/fonts', `preview-${name}.png`);
  fs.writeFileSync(out, encodePNG(W * k, H * k, px));
  console.log('preview', out);
}
