// high-tech split from RESEARCH.md ("Planted tanks"): 1 low light no CO2, 3 high light with CO2.
import type { ItemDef, PlantSpec, Placement, Shape, Water, RegionId } from './types';
import type { RampName } from './palette';

interface PlantIn {
  id: string;
  name: string;
  shape: Shape;
  colors: RampName[];
  plant: PlantSpec;
  w: number;
  h: number;
  place?: Placement;
  water?: Water[];
  regions?: RegionId[];
  price?: number;
  tier?: number;
  blurb: string;
  source?: 'supplier' | 'expedition';
}

function pl(p: PlantIn): ItemDef {
  const water: Water[] = p.water ?? (p.plant.salt ? ['fresh', 'brackish'] : ['fresh']);
  const place: Placement =
    p.place ?? (p.plant.epiphyte ? 'attach' : p.plant.kind === 'floating' ? 'surface' : p.plant.kind === 'carpet' ? 'carpet' : 'ground');
  return {
    id: p.id, name: p.name, cat: 'plant', water, regions: p.regions,
    price: p.price ?? 4 + p.plant.light * 3 + p.plant.co2 * 3,
    tier: p.tier ?? 0, w: p.w, h: p.h, place, shape: p.shape, colors: p.colors, plant: p.plant,
    blurb: p.blurb, source: p.source ?? 'supplier',
  };
}

